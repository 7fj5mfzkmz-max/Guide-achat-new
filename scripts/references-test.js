const assert=require('node:assert/strict');
const refs=require('../phone-analyzer/references.js');
const engine=require('../phone-analyzer/spec-score.js');
const insights=require('../phone-analyzer/spec-insights.js');
assert.equal(engine.criteria({}, {}, null).photo,null);
const sample={specs:{processeur:'Snapdragon 8 Elite',ram:'16 Go',ecran:'AMOLED 144 Hz',batterie:'6000 mAh',charge:'100 W',stockage:'512 Go'},modelName:'Synthetic Ultra'};
const before=engine.estimate(sample);
assert(before.profiles.gamer.score<=7.4);
refs.install({phones:[{id:'synthetic',model:'Synthetic Ultra',aliases:[],evidence:[{domain:'gaming',source:'Synthetic test',url:'https://example.com/test',date:'2026-10-13',status:'validated',kind:'measured',score_10:9.5,method:'Synthetic fixture'}]}]});
const after=engine.estimate(sample);
assert.equal(after.criteria.gaming,9.5);
assert(after.profiles.gamer.score>before.profiles.gamer.score);
const ramGamer=insights.verdict('gamer','ram','8 Go',{apple:false});
assert.equal(ramGamer.level,'warn');
const ramPro=insights.verdict('professionnel','ram','8 Go',{});
assert.equal(ramPro.level,'good');
const photo=insights.verdict('photographe','photo','50 MP, OIS, telephoto',{});
assert.equal(photo.level,'good');
console.log('Final execution tests passed',ramGamer.label,ramPro.label,photo.label);
